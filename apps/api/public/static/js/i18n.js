  function getLocale() {
    return localStorage.getItem('hufra_locale') || 'ar';
  }

  function setLocale(locale) {
    localStorage.setItem('hufra_locale', locale);
    applyDocumentDirection(locale);
  }

  function applyDocumentDirection(locale) {
    var dir = locale === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('lang', locale);
    document.documentElement.setAttribute('dir', dir);
  }

  function t(key) {
    var locale = getLocale();
    var dict = STRINGS[locale] || STRINGS.ar;
    return dict[key] || STRINGS.ar[key] || key;
  }

  function translatePage(root) {
    var scope = root || document;
    var nodes = scope.querySelectorAll('[data-i18n]');
    nodes.forEach(function (node) {
      var key = node.getAttribute('data-i18n');
      node.textContent = t(key);
    });
    var htmlNodes = scope.querySelectorAll('[data-i18n-html]');
    htmlNodes.forEach(function (node) {
      var key = node.getAttribute('data-i18n-html');
      node.innerHTML = t(key);
    });
    var placeholderNodes = scope.querySelectorAll('[data-i18n-placeholder]');
    placeholderNodes.forEach(function (node) {
      node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
    });
    var ariaNodes = scope.querySelectorAll('[data-i18n-aria-label]');
    ariaNodes.forEach(function (node) {
      node.setAttribute('aria-label', t(node.getAttribute('data-i18n-aria-label')));
    });
  }

  global.HufraI18n = {
    t: t,
    getLocale: getLocale,
    setLocale: setLocale,
    applyDocumentDirection: applyDocumentDirection,
    translatePage: translatePage,
  };

  applyDocumentDirection(getLocale());
