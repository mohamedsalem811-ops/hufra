// Generates public/static/js/icons.js: a tiny self-hosted replacement for the
// unpkg `lucide` UMD bundle. It exposes window.lucide.createIcons() with the
// same <i data-lucide="name"> contract, but only ships the icons HUFRA uses.
// Source of truth: the pinned `lucide-static` devDependency (ISC license).
// Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const ICONS = [
  // navigation / chrome
  'house', 'map', 'circle-plus', 'plus', 'user', 'shield-check', 'bell', 'languages', 'moon', 'sun',
  'a-large-small', 'sliders-horizontal', 'menu', 'x', 'chevron-left', 'chevron-right', 'chevron-down',
  'arrow-left', 'arrow-right', 'log-in', 'log-out', 'settings', 'info', 'lock', 'shield', 'list-filter',
  // map / report
  'locate-fixed', 'map-pin', 'layers', 'navigation', 'camera', 'image-plus', 'sparkles', 'send', 'check',
  'circle-check', 'triangle-alert', 'wifi-off', 'cloud-off', 'refresh-cw', 'flag',
  // content
  'file-text', 'wrench', 'clock', 'activity', 'inbox', 'heart-handshake', 'award', 'thumbs-up', 'share-2',
  'message-circle', 'download', 'trash-2', 'mail', 'eye', 'ellipsis', 'type', 'globe', 'scale', 'users',
  // legacy names still referenced in markup (aliases exist in lucide-static)
  'home', 'plus-circle', 'check-circle', 'alert-triangle', 'case-sensitive',
]

// Resolve the package wherever npm installed it (workspaces hoist to the repo root).
const dir = new URL('./icons/', import.meta.resolve('lucide-static/package.json'))
const out = {}
for (const name of ICONS) {
  let svg
  try { svg = readFileSync(new URL(`${name}.svg`, dir), 'utf8') } catch { console.warn('missing icon:', name); continue }
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
  out[name] = inner.replace(/\s+/g, ' ').replace(/> </g, '><').trim()
}

const js = `// AUTO-GENERATED by scripts/build-icons.mjs - do not edit by hand.
// Self-hosted subset of Lucide (https://lucide.dev, ISC license). Replaces the
// unpinned unpkg CDN script so the app renders icons with no network access.
(function (global) {
  'use strict';
  var ICONS = ${JSON.stringify(out)};
  var NS = 'http://www.w3.org/2000/svg';

  function createIcons(root) {
    var scope = root && root.querySelectorAll ? root : document;
    var nodes = scope.querySelectorAll('i[data-lucide]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var name = el.getAttribute('data-lucide');
      var body = ICONS[name];
      if (!body) continue;
      var svg = document.createElementNS(NS, 'svg');
      svg.setAttribute('xmlns', NS);
      svg.setAttribute('viewBox', '0 0 24 24');
      svg.setAttribute('fill', 'none');
      svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', '2');
      svg.setAttribute('stroke-linecap', 'round');
      svg.setAttribute('stroke-linejoin', 'round');
      svg.setAttribute('class', ('lucide lucide-' + name + ' ' + (el.getAttribute('class') || '')).trim());
      svg.setAttribute('data-icon', name);
      if (el.getAttribute('aria-label')) { svg.setAttribute('aria-label', el.getAttribute('aria-label')); svg.setAttribute('role', 'img'); }
      else svg.setAttribute('aria-hidden', 'true');
      if (el.id) svg.id = el.id;
      if (el.getAttribute('style')) svg.setAttribute('style', el.getAttribute('style'));
      svg.innerHTML = body;
      if (el.parentNode) el.parentNode.replaceChild(svg, el);
    }
  }

  global.lucide = { createIcons: createIcons, icons: ICONS };
})(window);
`
writeFileSync(new URL('../public/static/js/icons.js', import.meta.url), js)
console.log('icons:', Object.keys(out).length, 'bytes:', js.length)
