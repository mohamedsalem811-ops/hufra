// Turns the token source (tokens.ts) into the files other apps consume:
//   dist/tokens.css   CSS custom properties (admin panel, website)
//   dist/tokens.json  flat JSON (tools, design canvas)
//   dist/preview.html a visual sheet of every token, for review
// Pure functions, so the test suite can check that dist/ is up to date.

import { contrastRatio, CONTRAST_PAIRS } from './contrast'
import {
  dark,
  elevation,
  fontFamily,
  light,
  motion,
  palette,
  radius,
  rules,
  shadowColor,
  space,
  touchTarget,
  typeScale,
  type ColorTheme,
} from './tokens'

const HEADER = '/* GENERATED by packages/brand (npm run build -w @hufra/brand). Do not edit: change src/tokens.ts. */\n'

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

/** Flatten a colour theme into [cssVarName, value] pairs: bg.canvas -> --color-bg-canvas. */
export function themeVars(theme: ColorTheme): Array<[string, string]> {
  const out: Array<[string, string]> = []
  const walk = (obj: Record<string, unknown>, path: string[]) => {
    for (const [k, v] of Object.entries(obj)) {
      if (typeof v === 'string') out.push([`--color-${[...path, k].map(kebab).join('-')}`, v])
      else walk(v as Record<string, unknown>, [...path, k])
    }
  }
  walk(theme as unknown as Record<string, unknown>, [])
  return out
}

function hexToRgb(hex: string): string {
  const n = parseInt(hex.slice(1), 16)
  return `${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}`
}

function staticVars(): Array<[string, string]> {
  const v: Array<[string, string]> = []
  v.push(['--font-sans', `'${fontFamily.sans}', ${fontFamily.fallback}`])
  for (const [name, t] of Object.entries(typeScale)) {
    const n = kebab(name)
    v.push([`--text-${n}-size`, `${t.size / 16}rem`])
    v.push([`--text-${n}-line`, `${t.lineHeight / 16}rem`])
    v.push([`--text-${n}-weight`, String(t.weight)])
  }
  for (const [k, px] of Object.entries(space)) v.push([`--space-${k}`, `${px / 16}rem`])
  for (const [k, px] of Object.entries(radius)) v.push([`--radius-${k}`, `${px}px`])
  for (const [k, e] of Object.entries(elevation)) {
    v.push([`--shadow-${k}`, e.opacity === 0 ? 'none' : `0 ${e.y}px ${e.blur}px rgba(${hexToRgb(shadowColor)}, ${e.opacity})`])
  }
  for (const [k, ms] of Object.entries(motion.duration)) v.push([`--duration-${k}`, `${ms}ms`])
  for (const [k, c] of Object.entries(motion.easing)) v.push([`--ease-${k}`, `cubic-bezier(${c.join(', ')})`])
  v.push(['--touch-target', `${touchTarget}px`])
  return v
}

const block = (selector: string, vars: Array<[string, string]>, indent = '') =>
  `${indent}${selector} {\n${vars.map(([k, val]) => `${indent}  ${k}: ${val};`).join('\n')}\n${indent}}\n`

export function toCss(): string {
  return (
    HEADER +
    '\n/* Scales (theme-independent) */\n' +
    block(':root', staticVars()) +
    '\n/* Light theme (default) */\n' +
    block(':root', [['color-scheme', 'light'], ...themeVars(light)]) +
    '\n/* Dark theme: follows the system unless data-theme="light" is set on <html> */\n' +
    '@media (prefers-color-scheme: dark) {\n' +
    block(':root:not([data-theme="light"])', [['color-scheme', 'dark'], ...themeVars(dark)], '  ') +
    '}\n' +
    '\n/* Dark theme chosen explicitly */\n' +
    block(':root[data-theme="dark"]', [['color-scheme', 'dark'], ...themeVars(dark)])
  )
}

export function toJson(): string {
  return (
    JSON.stringify(
      {
        $generated: 'packages/brand: change src/tokens.ts, then npm run build -w @hufra/brand',
        name: 'HUFRA · Direction A · Civic Clarity',
        palette,
        themes: { light, dark },
        fontFamily,
        typeScale,
        space,
        radius,
        elevation,
        shadowColor,
        motion,
        touchTarget,
        rules,
      },
      null,
      2
    ) + '\n'
  )
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function themePanel(name: string, theme: ColorTheme): string {
  const swatches = themeVars(theme)
    .map(
      ([k, v]) =>
        `<div class="sw"><span class="chip" style="background:${v}"></span><code>${esc(k.replace('--color-', ''))}</code><small>${esc(v)}</small></div>`
    )
    .join('')
  const checks = CONTRAST_PAIRS.map((pair) => {
    const fg = pair.fg(theme)
    const bg = pair.bg(theme)
    const r = contrastRatio(fg, bg)
    return `<tr><td><span class="pairchip" style="color:${fg};background:${bg}">حفرة Aa</span></td><td>${esc(pair.name)}</td><td dir="ltr" class="${r >= pair.min ? 'ok' : 'bad'}">${r.toFixed(2)} : 1</td><td dir="ltr">≥ ${pair.min}</td></tr>`
  }).join('')
  const badges = (['reported', 'verified', 'underRepair', 'fixed'] as const)
    .map((s) => {
      const label = { reported: 'تم الإبلاغ', verified: 'تم التحقق', underRepair: 'قيد الإصلاح', fixed: 'تم الإصلاح' }[s]
      return `<span class="badge" style="color:${theme.status[s].fg};background:${theme.status[s].bg}"><i style="background:${theme.status[s].pin}"></i>${label}</span>`
    })
    .join('')
  return `<section class="panel" style="background:${theme.bg.canvas};color:${theme.text.primary}">
  <h2>${name}</h2>
  <div class="row">
    <button style="background:${theme.action.primary};color:${theme.action.onPrimary}">بلّغ عن حفرة</button>
    <button style="background:${theme.brand.primary};color:${theme.brand.onPrimary}">افتح الخريطة</button>
    <span style="color:${theme.text.link};text-decoration:underline">رابط · link</span>
  </div>
  <div class="card" style="background:${theme.bg.surface};border-color:${theme.border.default}">
    <div style="font-size:1.125rem;font-weight:600">[اسم الشارع] · [الحي]</div>
    <div style="color:${theme.text.secondary}">نص ثانوي · secondary text</div>
    <div class="row">${badges}</div>
  </div>
  <h3>Colour roles</h3><div class="grid">${swatches}</div>
  <h3>Contrast (WCAG 2.2 AA)</h3>
  <table>${checks}</table>
</section>`
}

